        }
        if let v = shenSha[name] {
            return GlossaryTerm(name: name, category: "神煞", brief: v.brief, detail: v.detail)
        }
        if let v = concepts[name] {
            return GlossaryTerm(name: name, category: "概念", brief: v.brief, detail: v.detail)
        }
        // 纳音名（如 白蜡金）：给通用兜底解释
        if NaYin.map.values.contains(name) {
            return GlossaryTerm(name: name, category: "纳音",
